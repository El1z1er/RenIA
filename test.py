from src.core.validators.validator import Validator

validator = Validator()


def test(title, routine, parameters, option=None):

    print("=" * 80)
    print(title)

    try:

        valid, errors = validator.validate(
            routine,
            parameters,
            option
        )

        print(f"Valid: {valid}")

        if errors:

            for error in errors:
                print(f"- {error}")

        else:
            print("No errors.")

    except Exception as e:

        print(type(e).__name__)
        print(e)


# ============================================================================
# VALID
# ============================================================================

test(
    "VALID",
    "P9814",
    {
        "D": 20,
        "F": 0.5,
        "S": 54
    },
    "Bore"
)


